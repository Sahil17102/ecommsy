export const SIGNATURE_GUIDE: GuideSection = {
  id: "webhook-signatures",
  title: "Verifying a signature",
  body: [
    "Every delivery carries an `X-Searchcraft-Signature` header:",
    "",
    "```",
    "X-Searchcraft-Signature: t=1756199673,v1=8f2c...e91",
    "```",
    "",
    "`t` is the send time in Unix seconds. `v1` is `HMAC-SHA256(secret, t + \".\" + rawBody)` in lowercase hex.",
    "",
    "Compute the same value over the **raw request body** — the exact bytes, before any JSON parsing or",
    "re-serialisation. Comparing a re-encoded body will fail for reasons that are painful to debug.",
    "",
    "Compare with a constant-time function, and reject anything whose `t` is more than a few minutes old:",
    "the timestamp is inside the signed string precisely so a captured delivery cannot be replayed later.",
    "",
    "The older `X-Webhook-Signature` header (a bare HMAC of the body, no timestamp) is still sent for",
    "backward compatibility. It is **deprecated** — it offers no replay protection. Verify `v1`.",
  ].join("\n"),
  samples: [
    {
      label: "Node.js",
      code: [
        "import crypto from 'node:crypto';",
        "import express from 'express';",
        "",
        "const app = express();",
        "",
        "// express.raw — the signature is over the bytes we received, not a re-encoding.",
        "app.post('/hooks/searchcraft', express.raw({ type: 'application/json' }), (req, res) => {",
        "  const header = req.get('X-Searchcraft-Signature') ?? '';",
        "  const parts = Object.fromEntries(header.split(',').map((p) => p.split('=')));",
        "",
        "  const expected = crypto",
        "    .createHmac('sha256', process.env.BOX_BEYOND_WEBHOOK_SECRET)",
        "    .update(`${parts.t}.${req.body.toString('utf8')}`)",
        "    .digest('hex');",
        "",
        "  const received = Buffer.from(parts.v1 ?? '', 'hex');",
        "  const computed = Buffer.from(expected, 'hex');",
        "  const signatureOk =",
        "    received.length === computed.length && crypto.timingSafeEqual(received, computed);",
        "  const fresh = Math.abs(Date.now() / 1000 - Number(parts.t)) < 300;",
        "",
        "  if (!signatureOk || !fresh) return res.status(400).send('invalid signature');",
        "",
        "  const event = JSON.parse(req.body.toString('utf8'));",
        "  // Store event.id and ack straight away — process afterwards.",
        "  if (!alreadySeen(event.id)) enqueue(event);",
        "  res.sendStatus(200);",
        "});",
      ].join("\n"),
    },
    {
      label: "Python",
      code: [
        "import hashlib, hmac, json, time",
        "from flask import Flask, request, abort",
        "",
        "app = Flask(__name__)",
        "SECRET = os.environ['BOX_BEYOND_WEBHOOK_SECRET'].encode()",
        "",
        "@app.post('/hooks/searchcraft')",
        "def box_and_beyond_webhook():",
        "    raw = request.get_data()  # raw bytes, not request.json",
        "    parts = dict(p.split('=', 1) for p in request.headers.get('X-Searchcraft-Signature', '').split(','))",
        "",
        "    signed = parts.get('t', '').encode() + b'.' + raw",
        "    expected = hmac.new(SECRET, signed, hashlib.sha256).hexdigest()",
        "",
        "    fresh = abs(time.time() - int(parts.get('t', 0))) < 300",
        "    if not fresh or not hmac.compare_digest(expected, parts.get('v1', '')):",
        "        abort(400)",
        "",
        "    event = json.loads(raw)",
        "    if not already_seen(event['id']):",
        "        enqueue(event)",
        "    return '', 200",
      ].join("\n"),
    },
    {
      label: "PHP",
      code: [
        "<?php",
        "$raw    = file_get_contents('php://input');   // raw body, not $_POST",
        "$header = $_SERVER['HTTP_X_BOX_AND_BEYOND_SIGNATURE'] ?? '';",
        "",
        "parse_str(str_replace(',', '&', $header), $parts);",
        "",
        "$expected = hash_hmac('sha256', $parts['t'] . '.' . $raw, getenv('BOX_BEYOND_WEBHOOK_SECRET'));",
        "$fresh    = abs(time() - (int) ($parts['t'] ?? 0)) < 300;",
        "",
        "if (!$fresh || !hash_equals($expected, $parts['v1'] ?? '')) {",
        "    http_response_code(400);",
        "    exit('invalid signature');",
        "}",
        "",
        "$event = json_decode($raw, true);",
        "if (!alreadySeen($event['id'])) {",
        "    enqueue($event);",
        "}",
        "http_response_code(200);",
      ].join("\n"),
    },
  ],
  table: {
    columns: ["Header", "Value"],
    rows: [
      ["X-Searchcraft-Event", "Event name, e.g. `order.delivered`."],
      ["X-Searchcraft-Event-Id", "`evt_…` — the same value as the envelope `id`. Stable across retries and across endpoints. De-duplicate on this."],
      ["X-Searchcraft-Delivery-Id", "Identifies this one attempt. Quote it to support, or find it in the panel under **Settings → Webhooks → View log**."],
      ["X-Searchcraft-Attempt", "Attempt number, `1` to `5`."],
      ["X-Searchcraft-Timestamp", "Send time, ISO-8601."],
      ["X-Searchcraft-Signature", "`t=<unix seconds>,v1=<hex HMAC-SHA256>`. Verify this."],
      ["X-Webhook-Signature", "Deprecated — bare HMAC of the body, no replay protection."],
      ["User-Agent", "`Searchcraft-Webhooks/1.0`"],
    ],
  },
};
