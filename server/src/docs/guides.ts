/**
 * Long-form prose for the docs page. Kept out of the OpenAPI document because
 * it is narrative rather than machine-readable, and out of the renderer
 * because the renderer is about layout.
 */

export interface GuideSection {
  id: string;
  title: string;
  /** Markdown subset — see docs/markdown.ts. */
  body: string;
  /** Optional labelled code samples rendered as a tab strip. */
  samples?: Array<{ label: string; code: string }>;
  /** Optional two-column reference table. */
  table?: { columns: string[]; rows: string[][] };
}

